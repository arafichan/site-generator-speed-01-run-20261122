const byCodeUnits = (a, b) => (a < b ? -1 : a > b ? 1 : 0);

// ---------------------------------------------------------------- text

const ESCAPES = { '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' };

/** `text` with & < > " and ' escaped. Fast path: no special char, no copy. */
export function escapeHtml(text) {
  let i = 0;
  const n = text.length;
  while (i < n) {
    const c = text.charCodeAt(i);
    if (c === 38 || c === 60 || c === 62 || c === 34 || c === 39) break;
    i++;
  }
  if (i === n) return text;
  let out = text.slice(0, i);
  for (; i < n; i++) {
    const ch = text[i];
    const rep = ESCAPES[ch];
    out += rep === undefined ? ch : rep;
  }
  return out;
}

/** Escape the range text[a..b) into the `out` array, without slicing. */
function escRange(text, a, b, out) {
  let i = a;
  while (i < b) {
    const c = text.charCodeAt(i);
    if (c === 38 || c === 60 || c === 62 || c === 34 || c === 39) break;
    i++;
  }
  if (i > a) out.push(text.slice(a, i));
  for (; i < b; i++) {
    const ch = text[i];
    const rep = ESCAPES[ch];
    out.push(rep === undefined ? ch : rep);
  }
}

export const SLUG_MAX = 64;

function slugLoop(plain) {
  let out = '';
  let gap = false;
  for (let i = 0; i < plain.length; i++) {
    const ch = plain[i];
    let keep = null;
    if (ch >= 'A' && ch <= 'Z') keep = ch.toLowerCase();
    else if ((ch >= 'a' && ch <= 'z') || (ch >= '0' && ch <= '9')) keep = ch;
    if (keep === null) {
      gap = out.length > 0;
      continue;
    }
    if (gap) out += '-';
    gap = false;
    out += keep;
  }
  out = out.slice(0, SLUG_MAX).replace(/-+$/, '');
  return out === '' ? 'untitled' : out;
}

/**
 * The slug of `text`: NFKD, combining marks dropped, A-Z lowered, every run of
 * characters other than a-z and 0-9 one "-", none at either end, at most 64
 * characters (a "-" left at the cut dropped), "untitled" when nothing is left.
 * Pure ASCII text is unchanged by NFKD and holds no combining marks, so it takes
 * the loop directly; anything else goes through the full normalisation.
 */
export function slugify(text) {
  let ascii = true;
  for (let i = 0; i < text.length; i++) {
    if (text.charCodeAt(i) > 127) {
      ascii = false;
      break;
    }
  }
  if (ascii) return slugLoop(text);
  const plain = text.normalize('NFKD').replace(/\p{M}/gu, '');
  // The reference iterates code points; reproduce that exactly for non-ASCII.
  let out = '';
  let gap = false;
  for (const ch of plain) {
    let keep = null;
    if (ch >= 'A' && ch <= 'Z') keep = ch.toLowerCase();
    else if ((ch >= 'a' && ch <= 'z') || (ch >= '0' && ch <= '9')) keep = ch;
    if (keep === null) {
      gap = out.length > 0;
      continue;
    }
    if (gap) out += '-';
    gap = false;
    out += keep;
  }
  out = out.slice(0, SLUG_MAX).replace(/-+$/, '');
  return out === '' ? 'untitled' : out;
}

/** `slug` made unique against `taken` (and added to it). */
export function uniqueSlug(slug, taken) {
  let out = slug;
  for (let n = 2; taken.has(out); n++) out = `${slug}-${n}`;
  taken.add(out);
  return out;
}

const MONTHS = ['January', 'February', 'March', 'April', 'May', 'June', 'July', 'August', 'September', 'October', 'November', 'December'];

/** A YYYY-MM-DD date in words, from the string alone. */
export function longDate(date) {
  const [y, m, d] = date.split('-');
  return `${Number(d)} ${MONTHS[Number(m) - 1]} ${y}`;
}

/** The words of lines[start..]: one native scan per line. */
function wordsOfLines(lines, start) {
  let n = 0;
  for (let i = start; i < lines.length; i++) {
    const m = lines[i].match(/\S+/g);
    if (m !== null) n += m.length;
  }
  return n;
}

// ---------------------------------------------------------------- front matter

export const KEYS = Object.freeze(['title', 'date', 'tags', 'draft', 'layout', 'slug', 'summary']);

const DATE = /^(\d{4})-(\d{2})-(\d{2})$/;
const NAME = /^[a-z0-9-]+$/;
const SLUG = /^[a-z0-9]+(?:-[a-z0-9]+)*$/;
const TAG = /^[^"[\]]+$/;

function daysIn(y, m) {
  if (m === 2) return (y % 4 === 0 && y % 100 !== 0) || y % 400 === 0 ? 29 : 28;
  return [4, 6, 9, 11].includes(m) ? 30 : 31;
}

function stringOf(raw) {
  if (raw.startsWith('"')) {
    if (raw.length < 2 || !raw.endsWith('"')) return { error: 'a quoted string is not closed' };
    let out = '';
    for (let i = 1; i < raw.length - 1; i++) {
      const c = raw[i];
      if (c === '\\') {
        const n = raw[i + 1];
        if ((n !== '"' && n !== '\\') || i + 1 === raw.length - 1) return { error: 'a quoted string holds an escape other than \\" or \\\\' };
        out += n;
        i++;
      } else if (c === '"') return { error: 'a quoted string holds a stray quote' };
      else out += c;
    }
    return { value: out };
  }
  if (raw.startsWith('[')) return { error: 'a bare string opens on [' };
  return { value: raw };
}

function valueOf(key, raw) {
  switch (key) {
    case 'title':
    case 'summary': {
      const s = stringOf(raw);
      return 'error' in s ? { error: `key "${key}": ${s.error}` } : s;
    }
    case 'date': {
      const m = DATE.exec(raw);
      const y = m ? Number(m[1]) : 0;
      const mo = m ? Number(m[2]) : 0;
      const d = m ? Number(m[3]) : 0;
      if (!m || y < 1970 || y > 2099 || mo < 1 || mo > 12 || d < 1 || d > daysIn(y, mo)) return { error: 'key "date": not a date from 1970-01-01 to 2099-12-31 (YYYY-MM-DD)' };
      return { value: raw };
    }
    case 'tags': {
      if (!raw.startsWith('[') || !raw.endsWith(']')) return { error: 'key "tags": not a list [a, b]' };
      const inner = raw.slice(1, -1);
      if (inner.trim() === '') return { value: [] };
      const tags = inner.split(',').map((t) => t.trim());
      if (tags.some((t) => t === '' || !TAG.test(t))) return { error: 'key "tags": an empty tag, or one holding " [ or ]' };
      return { value: tags };
    }
    case 'draft':
      return raw === 'true' ? { value: true } : raw === 'false' ? { value: false } : { error: 'key "draft": true or false' };
    case 'layout':
      return NAME.test(raw) ? { value: raw } : { error: 'key "layout": not a template name' };
    case 'slug':
      return SLUG.test(raw) && raw.length <= 64 ? { value: raw } : { error: 'key "slug": not a slug' };
    default:
      return { error: `unknown key "${key}"` };
  }
}

function isBlank(line) {
  for (let i = 0; i < line.length; i++) {
    const c = line.charCodeAt(i);
    if (c !== 32 && c !== 9) return false;
  }
  return true;
}

function rtrim(line) {
  let end = line.length;
  while (end > 0) {
    const c = line.charCodeAt(end - 1);
    if (c !== 32 && c !== 9) break;
    end--;
  }
  return line.slice(0, end);
}

/**
 * A source's front matter and body: { data, lines, start }, or { error } with
 * the first reason it is refused. `lines` is the source split on "\n" and
 * `start` the first body line, so the body is never joined into a new string.
 */
export function parseFrontMatter(text) {
  const lines = text.split('\n');
  if (lines[0] !== '---') return { error: 'no front matter' };
  let close = -1;
  for (let i = 1; i < lines.length; i++) {
    if (lines[i] === '---') {
      close = i;
      break;
    }
  }
  if (close === -1) return { error: 'the front matter is not closed' };
  const data = {};
  for (let i = 1; i < close; i++) {
    const line = lines[i];
    if (isBlank(line) || line.startsWith('#')) continue;
    // "key: value": a key of a-z and _, a colon, one space and the value.
    const ci = line.indexOf(':');
    if (ci <= 0) return { error: `line ${i + 1} is not "key: value"` };
    const key = line.slice(0, ci);
    let keyOk = true;
    for (let k = 0; k < key.length; k++) {
      const c = key.charCodeAt(k);
      if (!((c >= 97 && c <= 122) || c === 95)) {
        keyOk = false;
        break;
      }
    }
    if (!keyOk) return { error: `line ${i + 1} is not "key: value"` };
    const rest = line.slice(ci + 1);
    if (rest !== '' && rest.charCodeAt(0) !== 32) return { error: `line ${i + 1} is not "key: value"` };
    const raw = rtrim(rest === '' ? '' : rest.slice(1));
    if (!KEYS.includes(key)) return { error: `unknown key "${key}"` };
    if (Object.hasOwn(data, key)) return { error: `key "${key}" is given twice` };
    if (raw === '') return { error: `key "${key}" has no value` };
    const v = valueOf(key, raw);
    if ('error' in v) return v;
    data[key] = v.value;
  }
  if (!Object.hasOwn(data, 'title')) return { error: 'no title' };
  return { data, lines, start: close + 1 };
}

// ---------------------------------------------------------------- markdown

const FENCE_OPEN = /^```([A-Za-z0-9_+-]*)[ \t]*$/;
const FENCE_CLOSE = /^```[ \t]*$/;
const HEADING = /^(#{1,6})[ \t]+(.*?)[ \t]*$/;

function isFenceOpen(line) {
  if (!line.startsWith('```')) return null;
  return FENCE_OPEN.exec(line);
}

function isFenceClose(line) {
  if (!line.startsWith('```')) return false;
  return FENCE_CLOSE.test(line);
}

function isHr(line) {
  const c = line.charCodeAt(0);
  if (c !== 45 && c !== 42) return false; // '-' or '*'
  const mark = c === 45 ? '---' : '***';
  if (!line.startsWith(mark)) return false;
  for (let i = 3; i < line.length; i++) {
    const d = line.charCodeAt(i);
    if (d !== 32 && d !== 9) return false;
  }
  return true;
}

function headingOf(line) {
  if (line.charCodeAt(0) !== 35) return null; // '#'
  const m = HEADING.exec(line);
  return m === null || m[2] === '' ? null : { depth: m[1].length, text: m[2] };
}

/** Whether `line` ends a paragraph: a blank line, a fence, a heading or a thematic break. */
function endsParagraph(line) {
  return isBlank(line) || isFenceOpen(line) !== null || headingOf(line) !== null || isHr(line);
}

const trimLine = (line) => {
  let a = 0;
  let b = line.length;
  while (a < b && (line.charCodeAt(a) === 32 || line.charCodeAt(a) === 9)) a++;
  while (b > a && (line.charCodeAt(b - 1) === 32 || line.charCodeAt(b - 1) === 9)) b--;
  return line.slice(a, b);
};

const CONTINUED = /^ {2,}\S/;

/** A list item's marker on `line`: { ordered, num, text } or null. */
function listMarker(line) {
  const c0 = line.charCodeAt(0);
  if ((c0 === 45 || c0 === 42) && line.charCodeAt(1) === 32) return { ordered: false, num: 0, text: line.slice(2) };
  if (c0 >= 48 && c0 <= 57) {
    let i = 0;
    while (i < line.length && line.charCodeAt(i) >= 48 && line.charCodeAt(i) <= 57) i++;
    if (i >= 1 && i <= 9 && line.charCodeAt(i) === 46 && line.charCodeAt(i + 1) === 32) {
      return { ordered: true, num: Number(line.slice(0, i)), text: line.slice(i + 2) };
    }
  }
  return null;
}

/** `lines[start..]`'s block tokens, in order. */
export function lex(lines, start) {
  const tokens = [];
  let i = start;
  while (i < lines.length) {
    const line = lines[i];
    if (isBlank(line)) {
      i++;
      continue;
    }
    const fence = isFenceOpen(line);
    if (fence !== null) {
      const body = [];
      i++;
      while (i < lines.length && !isFenceClose(lines[i])) body.push(lines[i++]);
      i++;
      tokens.push({ type: 'code', lang: fence[1], lines: body });
      continue;
    }
    const heading = headingOf(line);
    if (heading !== null) {
      tokens.push({ type: 'heading', depth: heading.depth, text: heading.text });
      i++;
      continue;
    }
    if (isHr(line)) {
      tokens.push({ type: 'hr' });
      i++;
      continue;
    }
    if (line.charCodeAt(0) === 62) {
      // '>'
      const body = [];
      while (i < lines.length && lines[i].charCodeAt(0) === 62) {
        const l = lines[i++];
        body.push(l.charCodeAt(1) === 32 ? l.slice(2) : l.slice(1));
      }
      tokens.push({ type: 'blockquote', lines: body.map(trimLine).filter((l) => l !== '') });
      continue;
    }
    const marker = listMarker(line);
    if (marker !== null) {
      const isOrdered = marker.ordered;
      const start = marker.num;
      const items = [];
      while (i < lines.length) {
        const m = listMarker(lines[i]);
        if (m !== null && m.ordered === isOrdered) {
          items.push([trimLine(m.text)]);
          i++;
        } else if (CONTINUED.test(lines[i])) {
          items[items.length - 1].push(trimLine(lines[i]));
          i++;
        } else break;
      }
      tokens.push({ type: 'list', ordered: isOrdered, start: isOrdered ? start : 1, items: items.map((parts) => parts.join('\n')) });
      continue;
    }
    const body = [trimLine(line)];
    i++;
    while (i < lines.length && !endsParagraph(lines[i])) body.push(trimLine(lines[i++]));
    tokens.push({ type: 'paragraph', text: body.join('\n') });
  }
  return tokens;
}

/** Whether a backslash escapes `c`. */
function isEscapable(c) {
  return c === '\\' || c === '`' || c === '*' || c === '_' || c === '[' || c === ']' || c === '(' || c === ')' || c === '#' || c === '+' || c === '-' || c === '.' || c === '!' || c === '>';
}

/** The first index in [from, end) where `s` holds `what` outside a backslash escape, or -1. */
function findUnescaped(s, what, from, end) {
  const wlen = what.length;
  for (let j = from; j + wlen <= end; j++) {
    if (s[j] === '\\' && j + 1 < end && isEscapable(s[j + 1])) {
      j++;
      continue;
    }
    if (s[j] === what[0] && (wlen === 1 || s.startsWith(what, j))) return j;
  }
  return -1;
}

/** The first single * in [from, end) (one whose run is not **), outside an escape, or -1. */
function findSingleStar(s, from, end) {
  for (let j = from; j < end; j++) {
    const c = s[j];
    if (c === '\\' && j + 1 < end && isEscapable(s[j + 1])) {
      j++;
      continue;
    }
    if (c !== '*') continue;
    if (j + 1 < end && s[j + 1] === '*') {
      j++;
      continue;
    }
    return j;
  }
  return -1;
}

/**
 * Render the range s[a..b) inline into `out` (an array of strings); `env.link`
 * resolves a link's target. Identical output to the reference's recursive inline
 * renderer, but without copying substrings: nested constructs render into the
 * same output array over sub-ranges of the same string.
 */
export function inlineRange(s, env, out, a, b) {
  let seg = a;
  let i = a;
  while (i < b) {
    const code = s.charCodeAt(i);
    if (code === 92 || code === 96 || code === 42 || code === 91) {
      if (i > seg) out.push(s.slice(seg, i));
      const c = s[i];
      if (c === '\\') {
        if (i + 1 < b && isEscapable(s[i + 1])) {
          out.push(ESCAPES[s[i + 1]] ?? s[i + 1]);
          i += 2;
        } else {
          out.push('\\');
          i++;
        }
      } else if (c === '`') {
        const j = s.indexOf('`', i + 1);
        if (j !== -1 && j < b && j > i + 1) {
          out.push('<code>');
          escRange(s, i + 1, j, out);
          out.push('</code>');
          i = j + 1;
        } else {
          out.push('`');
          i++;
        }
      } else if (c === '*') {
        if (i + 1 < b && s[i + 1] === '*') {
          const j = findUnescaped(s, '**', i + 2, b);
          if (j !== -1 && j > i + 2) {
            out.push('<strong>');
            inlineRange(s, env, out, i + 2, j);
            out.push('</strong>');
            i = j + 2;
          } else {
            out.push('**');
            i += 2;
          }
        } else {
          const j = findSingleStar(s, i + 1, b);
          if (j !== -1 && j > i + 1) {
            out.push('<em>');
            inlineRange(s, env, out, i + 1, j);
            out.push('</em>');
            i = j + 1;
          } else {
            out.push('*');
            i++;
          }
        }
      } else {
        // '['
        const k = findUnescaped(s, ']', i + 1, b);
        let m = -1;
        if (k !== -1 && k + 1 < b && s[k + 1] === '(') {
          const r = s.indexOf(')', k + 2);
          if (r !== -1 && r < b) m = r;
        }
        if (m !== -1) {
          const target = s.slice(k + 2, m);
          if (target !== '' && !/\s/.test(target)) {
            out.push('<a href="');
            out.push(escapeHtml(env.link(target)));
            out.push('">');
            inlineRange(s, env, out, i + 1, k);
            out.push('</a>');
            i = m + 1;
          } else {
            out.push('[');
            i++;
          }
        } else {
          out.push('[');
          i++;
        }
      }
      seg = i;
      continue;
    }
    if (code === 38 || code === 60 || code === 62 || code === 34 || code === 39) {
      if (i > seg) out.push(s.slice(seg, i));
      out.push(ESCAPES[s[i]]);
      i++;
      seg = i;
      continue;
    }
    i++;
  }
  if (b > seg) out.push(s.slice(seg, b));
}

/** `s` rendered inline as a string. Fast path: no inline construct at all. */
export function inlineStr(s, env) {
  const n = s.length;
  let i = 0;
  let htmlSpecial = false;
  while (i < n) {
    const code = s.charCodeAt(i);
    if (code === 92 || code === 96 || code === 42 || code === 91) {
      const out = [];
      inlineRange(s, env, out, 0, n);
      return out.join('');
    }
    if (!htmlSpecial && (code === 38 || code === 60 || code === 62 || code === 34 || code === 39)) htmlSpecial = true;
    i++;
  }
  return htmlSpecial ? escapeHtml(s) : s;
}

/**
 * `lines[start..]` rendered: its HTML (each block on its own lines, a "\n"
 * after the last), its table of contents (every level 2 and 3 heading: level,
 * id and its inline HTML) and its excerpt (the first paragraph's inline HTML,
 * or "").
 */
export function renderMarkdown(lines, start, env) {
  const ids = new Set();
  const blocks = [];
  const toc = [];
  let excerpt = null;
  for (const t of lex(lines, start)) {
    switch (t.type) {
      case 'heading': {
        const id = uniqueSlug(slugify(t.text), ids);
        const html = inlineStr(t.text, env);
        blocks.push(`<h${t.depth} id="${id}">${html}</h${t.depth}>`);
        if (t.depth === 2 || t.depth === 3) toc.push({ level: t.depth, id, html });
        break;
      }
      case 'code': {
        const cls = t.lang === '' ? '' : ` class="language-${escapeHtml(t.lang)}"`;
        let inner = '';
        for (const l of t.lines) inner += `${escapeHtml(l)}\n`;
        blocks.push(`<pre><code${cls}>${inner}</code></pre>`);
        break;
      }
      case 'hr':
        blocks.push('<hr>');
        break;
      case 'blockquote':
        blocks.push(t.lines.length === 0 ? '<blockquote>\n</blockquote>' : `<blockquote>\n<p>${inlineStr(t.lines.join('\n'), env)}</p>\n</blockquote>`);
        break;
      case 'list': {
        const tag = t.ordered ? 'ol' : 'ul';
        const open = t.ordered && t.start !== 1 ? `<ol start="${t.start}">` : `<${tag}>`;
        let inner = '';
        for (const item of t.items) inner += `<li>${inlineStr(item, env)}</li>\n`;
        blocks.push(`${open}\n${inner}</${tag}>`);
        break;
      }
      case 'paragraph': {
        const html = inlineStr(t.text, env);
        if (excerpt === null) excerpt = html;
        blocks.push(`<p>${html}</p>`);
        break;
      }
    }
  }
  return { html: blocks.length === 0 ? '' : `${blocks.join('\n')}\n`, toc, excerpt: excerpt ?? '' };
}

